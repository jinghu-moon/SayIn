"""Generate the checked-in Tabler outline subset. No network or third-party modules.

Generator version: 1. Source SVGs and MIT license live in android/design/tabler/.
Only 24x24, unfilled, round-stroke path SVGs are supported. New shapes fail rather
than silently disappearing. Run from any directory with Python 3.11+.
"""

from hashlib import sha256
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "android/design/tabler"
OUTPUT = ROOT / "android/app/src/main/java/seeyuer/sayin/designsystem/icon/TablerVectors.kt"
ICONS = {
    "Keyboard": "keyboard",
    "Computer": "device-desktop",
    "Send": "send",
    "Microphone": "microphone",
    "History": "history",
    "Settings": "settings",
    "Scan": "scan",
    "Wifi": "wifi",
    "Check": "check",
    "Alert": "alert-triangle",
    "Shield": "shield-lock",
    "Close": "x",
    "Stop": "player-stop",
    "Clear": "trash",
    "ChevronRight": "chevron-right",
    "ChevronDown": "chevron-down",
    "Cloud": "cloud",
    "Phone": "device-mobile",
    "More": "dots-vertical",
    "Undo": "arrow-back-up",
    "Redo": "arrow-forward-up",
    "Translate": "language",
    "Copy": "copy",
    "Automatic": "bolt",
    "ArrowUp": "arrow-up",
    "Retry": "refresh",
    "Photo": "photo",
}


def generate() -> None:
    manifest = json.loads((SOURCE / "provenance.json").read_text(encoding="utf-8"))
    declarations = []
    for semantic, name in ICONS.items():
        data = (SOURCE / f"{name}.svg").read_bytes()
        if sha256(data).hexdigest() != manifest["svg_sha256"][name]:
            raise ValueError(f"Source hash mismatch: {name}")
        svg = ET.fromstring(data)
        expected = {"viewBox": "0 0 24 24", "fill": "none", "stroke": "currentColor",
                    "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round"}
        if any(svg.get(key) != value for key, value in expected.items()):
            raise ValueError(f"Unsupported SVG style: {name}")
        paths = []
        for child in svg:
            if child.tag != "{http://www.w3.org/2000/svg}path" or set(child.attrib) != {"d"}:
                raise ValueError(f"Unsupported SVG element: {name}: {child.tag}")
            paths.append(json.dumps(child.attrib["d"]))
        declarations.append(
            f"    val {semantic}: ImageVector by lazy {{\n"
            f'        outline("Tabler.{name}",\n'
            + ",\n".join(f"            {path}" for path in paths)
            + "\n        )\n    }"
        )
    header = """// Generated by scripts/generate_tabler_icons.py v1. Do not edit.
// Tabler Icons v3.51.0, MIT. See android/design/tabler/LICENSE and provenance.json.
package seeyuer.sayin.designsystem.icon

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

internal object TablerVectors {
"""
    footer = """
    private fun outline(name: String, vararg paths: String): ImageVector =
        ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {
            paths.forEach { path ->
                addPath(
                    pathData = PathParser().parsePathString(path).toNodes(),
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = 2f,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }
        }.build()
}
"""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(header + "\n\n".join(declarations) + "\n" + footer, encoding="utf-8")
    print(f"Generated {len(ICONS)} Tabler vectors: {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    generate()
